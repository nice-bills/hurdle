// Copies ../shared (deployment + ABIs, the single source of addresses) into src/shared as typed TS.
// If ../shared is absent (e.g. the app dir was deployed alone), the committed copy is kept.
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "..", "shared");
const out = join(here, "..", "src", "shared");
const pub = join(here, "..", "public", "abi");

if (!existsSync(join(src, "deployment-1301.json"))) {
  console.log("[sync-shared] ../shared not found, keeping committed src/shared");
  process.exit(0);
}
mkdirSync(out, { recursive: true });
mkdirSync(pub, { recursive: true });
const dep = JSON.parse(readFileSync(join(src, "deployment-1301.json"), "utf8"));
const header = "// GENERATED by scripts/sync-shared.mjs from app/shared. Do not edit.\n";
writeFileSync(join(out, "deployment.ts"), header + `export const deployment = ${JSON.stringify(dep, null, 2)} as const;\n`);

const names = { HurdleVault: "vaultAbi", HurdleVaultFactory: "factoryAbi", HurdleHook: "hookAbi", PoolSwapTest: "swapRouterAbi", MockERC20: "erc20Abi" };
let abis = header;
for (const f of readdirSync(join(src, "abi")).filter((f) => f.endsWith(".json")).sort()) {
  const base = f.replace(/\.json$/, "");
  const raw = readFileSync(join(src, "abi", f), "utf8");
  const abi = JSON.parse(raw);
  writeFileSync(join(pub, f), JSON.stringify(abi, null, 2));
  const name = names[base] ?? base[0].toLowerCase() + base.slice(1) + "Abi";
  abis += `export const ${name} = ${JSON.stringify(abi)} as const;\n`;
}
writeFileSync(join(out, "abis.ts"), abis);
writeFileSync(join(pub, "deployment-1301.json"), JSON.stringify(dep, null, 2));
console.log("[sync-shared] wrote src/shared/{deployment,abis}.ts and public/abi/*.json");
